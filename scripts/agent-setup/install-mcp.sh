#!/usr/bin/env bash
#
# install-mcp.sh
# Installs and initializes the required MCP servers for this project.
#
# Currently handles:
#   - code-review-graph  (installed + built for Codex and Claude Code)
#   - serena-agent       (installed + set up for Codex and Claude Code)
#   - ctx7               (set up via npx)
#   - ast-grep-cli       (installed via uv tool)
#   - ccusage            (token/cost monitor, warmed via npx)
#
# Usage:
#   ./install-mcp.sh
#

set -euo pipefail

# --- helpers ----------------------------------------------------------------

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m  ✓\033[0m %s\n' "$*"; }
err()  { printf '\033[1;31m  ✗\033[0m %s\n' "$*" >&2; }

require() {
  if ! command -v "$1" >/dev/null 2>&1; then
    err "Required command '$1' not found in PATH."
    exit 1
  fi
}

install_uv_tool() {
  local package binary
  package="$1"
  binary="$2"
  shift 2

  if [ "${FORCE_REINSTALL_AGENT_TOOLS:-0}" != "1" ] && command -v "$binary" >/dev/null 2>&1; then
    ok "$package already installed"
    return 0
  fi

  uv tool install --force --upgrade "$@" "$package"
  ok "$package installed"
}

serena_setup() {
  local client output status
  client="$1"

  set +e
  output="$(serena setup "$client" 2>&1)"
  status=$?
  set -e

  printf '%s\n' "$output"

  if [ "$status" -eq 0 ]; then
    return 0
  fi

  if printf '%s\n' "$output" | grep -qi "already exists"; then
    printf '\033[1;33m  ~\033[0m %s\n' "Serena MCP server already exists for $client - leaving it untouched."
    return 0
  fi

  return "$status"
}

# --- preflight --------------------------------------------------------------

log "Checking prerequisites"
require uv
ok "uv found ($(uv --version | awk '{print $2}'))"
require npx
ok "npx found ($(npx --version 2>/dev/null || echo '?'))"

# --- code-review-graph ------------------------------------------------------

log "Ensuring code-review-graph"
install_uv_tool code-review-graph code-review-graph

# The CLI is provided by the package above; make sure it's callable.
require code-review-graph

log "Installing code-review-graph for Codex"
code-review-graph install --platform codex
ok "Codex integration installed"

log "Installing code-review-graph for Claude Code"
code-review-graph install --platform claude-code
ok "Claude Code integration installed"

log "Building code-review-graph over the codebase"
code-review-graph build
ok "Build complete"

# --- serena-agent -----------------------------------------------------------

log "Ensuring serena-agent (Python 3.13)"
install_uv_tool serena-agent serena -p 3.13

# The CLI is provided by the tool above; make sure it's callable.
require serena

log "Initializing serena"
serena init
ok "serena initialized"

if [ ! -f ".serena/project.yml" ]; then
  log "Creating serena project config"
  serena project create --language php "$PWD"
  ok "serena project config created"
else
  ok "serena project config already exists"
fi

log "Setting up serena for Claude Code"
serena_setup claude-code
ok "Claude Code integration set up"

log "Setting up serena for Codex"
serena_setup codex
ok "Codex integration set up"

# --- ctx7 -------------------------------------------------------------------

log "Setting up ctx7"
npx --yes ctx7 setup --codex --claude --mcp --stdio --yes
ok "ctx7 set up"

# --- ast-grep-cli -----------------------------------------------------------

log "Ensuring ast-grep-cli"
install_uv_tool ast-grep-cli ast-grep

# Package provides the `ast-grep` binary (the `sg` alias clashes with the
# system `sg`/setgroup command on some distros, so we check `ast-grep`).
require ast-grep

# --- ccusage ----------------------------------------------------------------

log "Fetching ccusage (token/cost monitor)"
npx --yes ccusage@latest
ok "ccusage ready"

# --- .gitignore -------------------------------------------------------------
# Keep tool-generated state and per-user config out of the repo, so only your
# actual code (plus the shared CLAUDE.md / AGENTS.md context) gets committed.
#
# NOTE: the exact paths some tools generate can vary by version. The block
# below is conservative and clearly commented — review it against what the
# tools actually create in your repo and trim/extend as needed.

GITIGNORE_MARKER="# >>> agent-setup managed block >>>"

update_gitignore() {
  local repo_root gitignore
  repo_root="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
  gitignore="$repo_root/.gitignore"

  if [ -f "$gitignore" ] && grep -qF "$GITIGNORE_MARKER" "$gitignore"; then
    printf '\033[1;33m  ~\033[0m %s\n' ".gitignore already has the agent-setup block — leaving it untouched."
    return
  fi

  # Ensure a trailing newline before appending.
  if [ -f "$gitignore" ] && [ -n "$(tail -c1 "$gitignore" 2>/dev/null)" ]; then
    printf '\n' >> "$gitignore"
  fi

  cat >> "$gitignore" <<'EOF'

# >>> agent-setup managed block >>>
# Generated by scripts/agent-setup/install-mcp.sh — safe to edit, keep markers.

# --- Secrets / local env (never commit) ---
.env
.env.*
!.env.example

# --- Python tooling artifacts ---
__pycache__/
*.py[cod]
.venv/
venv/

# --- Node / npx debris ---
node_modules/
.npm/

# --- serena state (cache + per-session memory) ---
# If your team intends to SHARE serena project config, un-ignore it explicitly
# below, e.g.:  !.serena/project.yml
.serena/

# --- code-review-graph build/cache output ---
# Verify this path against what `code-review-graph build` actually writes.
.code-review-graph/

# --- Per-user MCP config that may contain tokens/keys ---
# Commit a sanitized, shared config separately if you want one in-repo.
.mcp.local.json
*.mcp.local.json

# NOTE: CLAUDE.md and AGENTS.md are intentionally NOT ignored — they are
# shared project context and should be committed.
# <<< agent-setup managed block <<<
EOF

  printf '\033[1;32m  ✓\033[0m %s\n' "Updated $gitignore"
}

log "Updating .gitignore"
update_gitignore

# --- done -------------------------------------------------------------------

log "All MCP servers installed and initialized."
